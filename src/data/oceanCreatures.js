export const filterCreatures = (query, category, size, habitat) => {
  return oceanCreatures.filter(c => {
    const matchesQuery = c.name.toLowerCase().includes(query.toLowerCase()) || 
                         c.funFact.toLowerCase().includes(query.toLowerCase());
    const matchesCategory = category === 'All' || c.category === category;
    const matchesSize = size === 'All' || c.size.includes(size);
    const matchesHabitat = habitat === 'All' || c.habitat === habitat;
    
    return matchesQuery && matchesCategory && matchesSize && matchesHabitat;
  });
};
